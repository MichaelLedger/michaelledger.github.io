  function detectLang() {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED_LANGS.indexOf(stored) !== -1) return stored;

    const browser = (navigator.language || '').toLowerCase();
    if (browser.startsWith('zh')) return 'zh';
    if (browser.startsWith('ja')) return 'ja';
    if (browser.startsWith('ko')) return 'ko';
    if (browser.startsWith('ru')) return 'ru';
    if (browser.startsWith('fr')) return 'fr';
    if (browser.startsWith('de')) return 'de';
    return 'en';
  }

  function applyLang(lang) {
    const strings = translations[lang];
    if (!strings) return;

    document.documentElement.lang = HTML_LANG[lang] || lang;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      const key = el.getAttribute('data-i18n');
      if (strings[key] !== undefined) {
        el.textContent = strings[key];
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      const key = el.getAttribute('data-i18n-html');
      if (strings[key] !== undefined) {
        el.innerHTML = strings[key];
      }
    });

    document.querySelectorAll('[data-i18n-mailto]').forEach(function (el) {
      const key = 'mailto.' + el.getAttribute('data-i18n-mailto');
      if (strings[key] !== undefined) {
        el.href = strings[key];
      }
    });

    const pageTitleKey = document.body.getAttribute('data-page-title');
    if (pageTitleKey && strings[pageTitleKey]) {
      document.title = strings[pageTitleKey];
    }

    const select = document.getElementById('lang-select');
    if (select) {
      select.value = lang;
    }

    localStorage.setItem(STORAGE_KEY, lang);
  }

  document.addEventListener('DOMContentLoaded', function () {
    applyLang(detectLang());

    const select = document.getElementById('lang-select');
    if (select) {
      select.addEventListener('change', function () {
        applyLang(select.value);
      });
    }
  });
